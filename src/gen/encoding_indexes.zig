/// Encoding index generator.
/// Source: https://encoding.spec.whatwg.org/indexes.json
const std = @import("std");
const Io = std.Io;

/// Arguments:
/// - args[1]: input JSON file containing WHATWG encoding indexes.
/// - args[2]: output Zig source file.
pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const arena = init.arena.allocator();
    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 3) {
        std.debug.print("Usage: {s} <input.json> <output.zig>\n", .{args[0]});
        std.process.exit(1);
    }

    const content = try Io.Dir.cwd().readFileAlloc(io, args[1], arena, .unlimited);
    var parsed = try std.json.parseFromSlice(std.json.Value, arena, content, .{});
    defer parsed.deinit();

    var output_file = try Io.Dir.cwd().createFile(io, args[2], .{});
    defer output_file.close(io);
    var buffer: [4096]u8 = undefined;
    var file_writer = output_file.writer(io, &buffer);
    const writer = &file_writer.interface;

    try writer.writeAll(
        \\// Code generated by build step (gen/encoding_indexes.zig). DO NOT EDIT.
        \\// Source: https://encoding.spec.whatwg.org/indexes.json
        \\
        \\
    );

    var entries = parsed.value.object.iterator();
    while (entries.next()) |entry| {
        const name = entry.key_ptr.*;
        // Only used by the ISO-2022-JP encoder, not the decoder.
        if (std.mem.eql(u8, name, "iso-2022-jp-katakana")) continue;
        const ranges = std.mem.eql(u8, name, "gb18030-ranges");
        const values = entry.value_ptr.array.items;

        try writer.writeAll("pub const ");
        for (name) |byte| try writer.writeByte(if (byte == '-') '_' else byte);
        try writer.print(" = [{d}]{s}{{\n", .{ values.len, if (ranges) "[2]u32" else "u21" });
        for (values, 0..) |value, i| {
            if (ranges) {
                const pair = value.array.items;
                try writer.print("    .{{ {d}, 0x{X} }},\n", .{ pair[0].integer, pair[1].integer });
            } else {
                const cp = switch (value) {
                    .null => 0,
                    .integer => |cp| blk: {
                        if (cp <= 0 or cp > 0x10FFFF or (cp >= 0xD800 and cp <= 0xDFFF))
                            return error.InvalidCodePoint;
                        break :blk cp;
                    },
                    else => return error.InvalidCodePoint,
                };
                if (i % 12 == 0) try writer.writeAll("    ");
                try writer.print("0x{X},", .{cp});
                try writer.writeByte(if (i % 12 == 11 or i + 1 == values.len) '\n' else ' ');
            }
        }
        try writer.writeAll("};\n\n");
    }

    try file_writer.flush();
    return std.process.cleanExit(io);
}
