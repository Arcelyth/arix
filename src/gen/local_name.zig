/// Local name generator.
const std = @import("std");
const Io = std.Io;

/// Arguments:
/// - args[1]: input JSON file containing local names.
/// - args[2]: output Zig source file.
pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const arena = init.arena.allocator();

    const args = try init.minimal.args.toSlice(arena);

    if (args.len < 3) fatal("Usage: {s} <input.json> <output.zig>\n", .{args[0]});

    const json_path = args[1];
    const output_file_path = args[2];

    const content = try std.Io.Dir.cwd().readFileAlloc(
        io,
        json_path,
        arena,
        .unlimited,
    );

    var parsed = try std.json.parseFromSlice(std.json.Value, arena, content, .{});
    defer parsed.deinit();

    const root_obj = parsed.value.object;
    const data_array = root_obj.get("data") orelse {
        fatal("JSON root must contain a 'data' array\n", .{});
    };

    var output_file = Io.Dir.cwd().createFile(io, output_file_path, .{}) catch |err| {
        fatal("unable to open '{s}': {s}", .{ output_file_path, @errorName(err) });
    };
    defer output_file.close(io);

    var buffer: [4096]u8 = undefined;
    var file_writer = output_file.writer(io, &buffer);
    var writer = &file_writer.interface;

    try writer.writeAll(
        \\// Generated code
        \\// Code generated by build step (gen/local_name.zig). DO NOT EDIT.
        \\
        \\const std = @import("std");
        \\const strale = @import("strale");
        \\const StraleUtf8Global = strale.StraleUtf8Global;
        \\
        \\pub const static_local_names: []const [:0]const u8 = &.{
        \\
    );

    for (data_array.array.items, 0..) |item, i| {
        if (i > 0) try writer.writeAll(", ");
        if (i % 10 == 0 and i != 0) try writer.writeAll("\n    ");
        try writer.print("\"{s}\"", .{item.string});
    }

    try writer.writeAll(
        \\
        \\};
        \\
        \\pub const LocalTag = block: {
        \\    @setEvalBranchQuota(1200);
        \\    var values: [static_local_names.len]u16 = undefined;
        \\    for (0..static_local_names.len) |i| {
        \\        values[i] = @intCast(i);
        \\    }
        \\    const const_values = values;
        \\
        \\    break :block @Enum(
        \\        u16,
        \\        .exhaustive,
        \\        static_local_names,
        \\        &const_values,
        \\    );
        \\};
        \\
        \\pub const LocalNameMap = std.StaticStringMap(LocalTag).initComptime(block: {
        \\    @setEvalBranchQuota(1200);
        \\    var kvs: [static_local_names.len]struct { []const u8, LocalTag } = undefined;
        \\    for (static_local_names, 0..) |name, i| {
        \\        kvs[i] = .{ name, @enumFromInt(i) };
        \\    }
        \\    break :block kvs;
        \\});
        \\
        \\pub const LocalName = union(enum) {
        \\    static: LocalTag,
        \\    dynamic: StraleUtf8Global,
        \\
        \\    pub fn deinit(self: *LocalName) void {
        \\        switch (self.*) {
        \\            .static => {},
        \\            .dynamic => |*dy| dy.deinit(),
        \\        }
        \\    }
        \\
        \\    pub inline fn fromTag(tag: LocalTag) LocalName {
        \\        return .{.static = tag}; 
        \\    }
        \\
        \\    pub inline fn fromSlice(s: []const u8) !LocalName {
        \\        if (LocalNameMap.get(s)) |tag| {
        \\            return .{ .static = tag };
        \\        }
        \\        return .{ .dynamic = try StraleUtf8Global.initSlice(s) };
        \\    }
        \\
        \\    pub inline fn slice(self: LocalName) []const u8 {
        \\        return switch (self) {
        \\            .static => |tag| static_local_names[@intFromEnum(tag)],
        \\            .dynamic => |dy| dy.slice(),
        \\        };
        \\    }
        \\    
        \\    pub inline fn toTag(self: LocalName) ?LocalTag {
        \\        return switch (self) {
        \\            .static => |tag| tag,
        \\            .dynamic => null,
        \\        }; 
        \\    }
        \\
        \\    pub inline fn eql(self: LocalName, other: LocalName) bool {
        \\        if (self == .static and other == .static) {
        \\            return self.static == other.static;
        \\        }
        \\        if (self == .dynamic and other == .dynamic) {
        \\            return self.dynamic.cmp(&other.dynamic);
        \\        }
        \\        return false;
        \\    }
        \\
        \\    pub inline fn is(self: LocalName, tag: LocalTag) bool {
        \\        return self == .static and self.static == tag;
        \\    }
        \\
        \\    pub inline fn oneOf(self: LocalName, tags: []const LocalTag) bool{
        \\        for (tags) |tag| {
        \\            if (self.is(tag)) return true;
        \\        }
        \\        return false;
        \\    }
        \\
        \\    pub fn isValidCustomElementName(self: LocalName) bool {
        \\        if (!self.isValidElementLocalName()) return false;
        \\  
        \\        const s = self.slice();
        \\        if (s[0] < 'a' or s[0] > 'z') return false;
        \\  
        \\        var has_hyphen = false;
        \\        for (s) |b| {
        \\            if (b >= 'A' and b <= 'Z') return false;
        \\            if (b == '-') has_hyphen = true;
        \\        }
        \\        if (!has_hyphen) return false;
        \\  
        \\        const reserved_names = [_][]const u8{
        \\            "annotation-xml",
        \\            "color-profile",
        \\            "font-face",
        \\            "font-face-src",
        \\            "font-face-uri",
        \\            "font-face-format",
        \\            "font-face-name",
        \\            "missing-glyph",
        \\        };
        \\  
        \\        inline for (reserved_names) |reserved| {
        \\            if (std.mem.eql(u8, s, reserved)) return false;
        \\        }
        \\  
        \\        return true;
        \\    }
        \\  
        \\    pub fn isValidElementLocalName(self: LocalName) bool {
        \\        const s = self.slice();
        \\        if (s.len == 0) return false;
        \\  
        \\        const first_byte = s[0];
        \\        if ((first_byte >= 'a' and first_byte <= 'z') or (first_byte >= 'A' and first_byte <= 'Z')) {
        \\            for (s) |b| {
        \\                switch (b) {
        \\                    ' ', '\t', '\n', '\r', 0x0C, 0x00, '/', '>' => return false,
        \\                    else => {},
        \\                }
        \\            }
        \\            return true;
        \\        }
        \\  
        \\        var utf8 = std.unicode.Utf8View.init(s) catch return false;
        \\        var iter = utf8.iterator();
        \\        const first_cp = iter.nextCodepoint() orelse return false;
        \\  
        \\        if (first_cp != ':' and first_cp != '_' and !(first_cp >= 0x80 and first_cp <= 0x10FFFF)) {
        \\            return false;
        \\        }
        \\  
        \\        while (iter.nextCodepoint()) |cp| {
        \\            const valid = switch (cp) {
        \\                'a'...'z', 'A'...'Z', '0'...'9', '-', '.', ':', '_' => true,
        \\                0x80...0x10FFFF => true,
        \\                else => false,
        \\            };
        \\            if (!valid) return false;
        \\        }
        \\  
        \\        return true;
        \\    }
        \\  
        \\    pub fn format(self: LocalName, writer: anytype) !void {
        \\        if (self == .static) try writer.print("{s}", .{@tagName(self.static)}) else try writer.print("{s}", .{self.dynamic.slice()});
        \\    }
        \\};
    );

    try file_writer.flush();
    return std.process.cleanExit(io);
}

fn fatal(comptime format: []const u8, args: anytype) noreturn {
    std.debug.print(format, args);
    std.process.exit(1);
}
