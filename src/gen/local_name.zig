/// Local name generator.
const std = @import("std");
const Io = std.Io;

/// Arguments:
/// - args[1]: input JSON file containing local names.
/// - args[2]: output Zig source file.
pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const arena = init.arena.allocator();

    const args = try init.minimal.args.toSlice(arena);

    if (args.len < 3) fatal("Usage: {s} <input.json> <output.zig>\n", .{args[0]});

    const json_path = args[1];
    const output_file_path = args[2];

    const content = try std.Io.Dir.cwd().readFileAlloc(
        io,
        json_path,
        arena,
        .unlimited,
    );

    var parsed = try std.json.parseFromSlice(std.json.Value, arena, content, .{});
    defer parsed.deinit();

    const root_obj = parsed.value.object;
    const data_array = root_obj.get("data") orelse {
        fatal("JSON root must contain a 'data' array\n", .{});
    };

    var output_file = Io.Dir.cwd().createFile(io, output_file_path, .{}) catch |err| {
        fatal("unable to open '{s}': {s}", .{ output_file_path, @errorName(err) });
    };
    defer output_file.close(io);

    var buffer: [4096]u8 = undefined;
    var file_writer = output_file.writer(io, &buffer);
    var writer = &file_writer.interface;

    try writer.writeAll(
        \\// Generated code
        \\// Code generated by build step (gen/local_name.zig). DO NOT EDIT.
        \\
        \\const std = @import("std");
        \\
        \\pub const static_local_names: []const [:0]const u8 = &.{
        \\
    );

    for (data_array.array.items, 0..) |item, i| {
        if (i > 0) try writer.writeAll(", ");
        if (i % 10 == 0 and i != 0) try writer.writeAll("\n    ");
        try writer.print("\"{s}\"", .{item.string});
    }

    try writer.writeAll(
        \\
        \\};
        \\
        \\pub const LocalTag = block: {
        \\    @setEvalBranchQuota(1200);
        \\    var values: [static_local_names.len]u16 = undefined;
        \\    for (0..static_local_names.len) |i| {
        \\        values[i] = @intCast(i);
        \\    }
        \\    const const_values = values;
        \\
        \\    break :block @Enum(
        \\        u16,
        \\        .exhaustive,
        \\        static_local_names,
        \\        &const_values,
        \\    );
        \\};
        \\
        \\pub const LocalNameMap = std.StaticStringMap(LocalTag).initComptime(block: {
        \\    @setEvalBranchQuota(1200);
        \\    var kvs: [static_local_names.len]struct { []const u8, LocalTag } = undefined;
        \\    for (static_local_names, 0..) |name, i| {
        \\        kvs[i] = .{ name, @enumFromInt(i) };
        \\    }
        \\    break :block kvs;
        \\});
        \\
        \\pub const LocalName = union(enum) {
        \\    static: LocalTag,
        \\    dynamic: []const u8,
        \\
        \\    pub inline fn fromSlice(slice: []const u8) LocalName {
        \\        if (LocalNameMap.get(slice)) |tag| {
        \\            return .{ .static = tag };
        \\        }
        \\        return .{ .dynamic = slice };
        \\    }
        \\
        \\    pub inline fn eql(self: LocalName, other: LocalName) bool {
        \\        if (self == .static and other == .static) {
        \\            return self.static == other.static;
        \\        }
        \\        if (self == .dynamic and other == .dynamic) {
        \\            return std.mem.eql(u8, self.dynamic, other.dynamic);
        \\        }
        \\        return false;
        \\    }
        \\
        \\    pub inline fn is(self: LocalName, tag: LocalTag) bool {
        \\        return self == .static and self.static == tag;
        \\    }
        \\};
        \\
    );

    try file_writer.flush();
    return std.process.cleanExit(io);
}

fn fatal(comptime format: []const u8, args: anytype) noreturn {
    std.debug.print(format, args);
    std.process.exit(1);
}
