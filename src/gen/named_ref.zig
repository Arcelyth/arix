/// Named character reference generator.
/// This file will generates a compact trie table for HTML named character references.
const std = @import("std");
const Io = std.Io;

const TempTrieNode = struct {
    char: u8,
    value: ?[]const u8 = null,
    children: std.AutoHashMap(u8, *TempTrieNode),
    child_start: u16 = 0,
    child_count: u8 = 0,

    fn create(allocator: std.mem.Allocator, char: u8) !*TempTrieNode {
        const node = try allocator.create(TempTrieNode);
        node.* = .{
            .char = char,
            .value = null,
            .children = std.AutoHashMap(u8, *TempTrieNode).init(allocator),
            .child_start = 0,
            .child_count = 0,
        };
        return node;
    }
};


/// Arguments:
/// - args[1]: input JSON file containing named character references.
/// - args[2]: output Zig source file.
pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const arena = init.arena.allocator();

    const args = try init.minimal.args.toSlice(arena);

    if (args.len < 3) fatal("Usage: {s} <input.json> <output.zig>\n", .{args[0]});

    const json_path = args[1];
    const output_file_path = args[2];

    var output_file = Io.Dir.cwd().createFile(io, output_file_path, .{}) catch |err| {
        fatal("unable to open '{s}': {s}", .{ output_file_path, @errorName(err) });
    };
    defer output_file.close(io);

    const content = try std.Io.Dir.cwd().readFileAlloc(
        io,
        json_path,
        arena,
        .unlimited,
    );

    var parsed = try std.json.parseFromSlice(std.json.Value, arena, content, .{});
    defer parsed.deinit();
    const root = try TempTrieNode.create(arena, 0);

    var it = parsed.value.object.iterator();
    while (it.next()) |entry| {
        var key = entry.key_ptr.*;
        if (std.mem.startsWith(u8, key, "&")) {
            key = key[1..];
        }
        const val_str = entry.value_ptr.object.get("characters").?.string;

        var current = root;
        for (key) |ch| {
            const gop = try current.children.getOrPut(ch);
            if (!gop.found_existing) {
                gop.value_ptr.* = try TempTrieNode.create(arena, ch);
            }
            current = gop.value_ptr.*;
        }
        current.value = val_str;
    }

    var flat_nodes: std.ArrayList(*TempTrieNode) = .empty;
    try flat_nodes.append(arena, root);

    var idx: usize = 0;
    while (idx < flat_nodes.items.len) : (idx += 1) {
        const curr = flat_nodes.items[idx];
        if (curr.children.count() > 0) {
            curr.child_start = @intCast(flat_nodes.items.len);
            curr.child_count = @intCast(curr.children.count());

            var keys = try arena.alloc(u8, curr.children.count());
            var key_i: usize = 0;
            var child_it = curr.children.iterator();
            while (child_it.next()) |c_entry| {
                keys[key_i] = c_entry.key_ptr.*;
                key_i += 1;
            }
            std.mem.sort(u8, keys, {}, std.sort.asc(u8));

            for (keys) |k| {
                const child_node = curr.children.get(k).?;
                try flat_nodes.append(arena, child_node);
            }
        } else {
            curr.child_start = 0;
            curr.child_count = 0;
        }
    }
    var buffer: [4096]u8 = undefined;
    var file_writer = output_file.writer(io, &buffer);
    var writer = &file_writer.interface;
    try writer.writeAll("// Generated code\n");
    try writer.writeAll("// Code generated by build step (gen/named_ref.zig). DO NOT EDIT.\n");
    try writer.writeAll("// Source: https://html.spec.whatwg.org/multipage/named-characters.html\n\n");
    try writer.writeAll("const std = @import(\"std\");\n\n");
    try writer.writeAll(
        \\pub const TrieNode = struct {
        \\    char: u8,
        \\    child_start: u16,
        \\    child_count: u8,
        \\    value: ?[]const u8,
        \\};
        \\
        \\
    );

    try writer.print("pub const trie_nodes = [{d}]TrieNode{{\n", .{flat_nodes.items.len});

    for (flat_nodes.items, 0..) |node, i| {
        try writer.writeAll("    .{ ");

        switch (node.char) {
            0 => try writer.writeAll(".char = 0, "),
            '\'' => try writer.writeAll(".char = '\\'', "),
            '\\' => try writer.writeAll(".char = '\\\\', "),
            else => try writer.print(".char = '{c}', ", .{node.char}),
        }

        try writer.print(".child_start = {d}, .child_count = {d}, .value = ", .{
            node.child_start,
            node.child_count,
        });

        if (node.value) |val| {
            try writer.writeByte('"');
            try std.zig.stringEscape(val, writer);
            try writer.writeByte('"');
        } else {
            try writer.writeAll("null");
        }

        try writer.print(" }}, // idx: {d}\n", .{i});
    }

    try writer.writeAll("};\n");
    try file_writer.flush();
    return std.process.cleanExit(io);
}

fn fatal(comptime format: []const u8, args: anytype) noreturn {
    std.debug.print(format, args);
    std.process.exit(1);
}
